// Writes migrations/0002_defaults.sql from the app's own engine and word filter,
// so the server and the app share one list of templates and blocked words.
import { writeFileSync, readFileSync } from 'node:fs';
import { QUANT } from '../../app/www/js/engine/quant.js';
import { REASONING } from '../../app/www/js/engine/reasoning.js';

const now = '2026-10-20T00:00:00.000Z';
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const lines = ['-- Default settings, question templates and the base word filter. Generated by scripts/gen-defaults.mjs.'];

const SETTINGS = {
  'switch.signups': true, 'switch.duels': true, 'switch.squads': true, 'switch.leagues': true,
  'switch.plus_purchases': true, 'switch.ads': false, 'switch.pause_all': false,
  'limit.free_duels_per_day': 3, 'limit.league_max_members': 5000, 'limit.squad_max_members': 8,
  'price.plus_paise': 9900,
  'flags.alert_after': 3, 'flags.pause_after': 10,
};
for (const [k, v] of Object.entries(SETTINGS)) {
  lines.push(`INSERT INTO settings (key, value, updated_at, updated_by) VALUES (${q(k)}, ${q(JSON.stringify(v))}, ${q(now)}, 'system');`);
  lines.push(`INSERT INTO settings_history (key, value, at, admin_id) VALUES (${q(k)}, ${q(JSON.stringify(v))}, ${q(now)}, 'system');`);
}
for (const t of [...QUANT, ...REASONING]) {
  const topic = QUANT.includes(t) ? 'quant' : 'reasoning';
  lines.push(`INSERT INTO templates (id, label, topic, status, updated_at, updated_by) VALUES (${q(t.id)}, ${q(t.label)}, ${q(topic)}, 'active', ${q(now)}, 'system');`);
}
const validate = readFileSync(new URL('../../app/www/js/validate.js', import.meta.url), 'utf8');
const blocked = JSON.parse(validate.match(/const BLOCKED = (\[[\s\S]*?\]);/)[1].replace(/'/g, '"').replace(/,\s*\]/, ']'));
for (const w of blocked) lines.push(`INSERT INTO word_filter (word, added_by, added_at) VALUES (${q(w)}, 'system', ${q(now)});`);

writeFileSync(new URL('../migrations/0002_defaults.sql', import.meta.url), lines.join('\n') + '\n');
console.log(`0002_defaults.sql: ${Object.keys(SETTINGS).length} settings, ${QUANT.length + REASONING.length} templates, ${blocked.length} words`);
